export const CHARACTER_LIST: CharacterConfig[] = Object.values(CHARACTERS);

export function getCharacterConfig(characterId?: string): CharacterConfig {
  if (characterId && CHARACTERS[characterId]) {
    return CHARACTERS[characterId];
  }
  return CHARACTERS.kenshin;
}

export function buildCharacterSkillsMeta(
  characterId: string,
  stanceOverride?: StanceId,
): { id: string; name: string; flowCost: number; cooldown: number; stance: StanceId }[] {
  const char = getCharacterConfig(characterId);
  return char.skills.map((sk) => ({
    id: sk.id,
    name: sk.name,
    flowCost: sk.flowCost,
    cooldown: sk.cooldown,
    stance: stanceOverride ?? sk.move.stance,
  }));
}
